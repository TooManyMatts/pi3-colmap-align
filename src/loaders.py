import os
import torch
import numpy as np
import pycolmap

def load_colmap_data(colmap_dir):
    """
    Uses pycolmap to load the sparse reconstruction.
    
    Returns:
        cameras: Dict {filename: center_xyz (np.array)}
        points:  np.array (Nx3) or None
        colors:  np.array (Nx3) or None
    """
    if not os.path.exists(colmap_dir):
        raise FileNotFoundError(f"COLMAP directory not found: {colmap_dir}")
        
    print(f"Loading COLMAP reconstruction from {colmap_dir}...")
    try:
        # Load reconstruction (works with .bin or .txt automatically)
        recon = pycolmap.Reconstruction(colmap_dir)
    except Exception as e:
        raise RuntimeError(f"Failed to load COLMAP reconstruction: {e}")

    # 1. Extract Camera Centers
    cameras = {}
    for img_id, img in recon.images.items():
        # .projection_center() computes the world coordinate center (-R^t * t)
        cameras[img.name] = img.projection_center()

    # 2. Extract Sparse Point Cloud (for visualization)
    points = []
    colors = []
    
    for p3d_id, p3d in recon.points3D.items():
        points.append(p3d.xyz)
        colors.append(p3d.color)
        
    if len(points) > 0:
        points = np.array(points, dtype=np.float32)
        colors = np.array(colors, dtype=np.uint8)
    else:
        points = None
        colors = None

    return cameras, points, colors


def load_pi3_results(pt_path):
    """
    Loads results.pt generated by the Pi3 inference script.
    
    Returns tuple: (points, conf, poses, colors)
    """
    if not os.path.exists(pt_path):
        raise FileNotFoundError(f"Pi3 results not found at {pt_path}")
        
    # Load to CPU to ensure compatibility regardless of machine
    results = torch.load(pt_path, map_location='cpu')
    
    points = results['points']       # (B, N, H, W, 3)
    conf = results['conf']           # (B, N, H, W, 1)
    poses = results['camera_poses']  # (B, N, 4, 4)
    
    # Handle colors: Pi3 doesn't always output 'images' in the result dict unless specified.
    # If missing, return white.
    B, N, H, W, _ = points.shape
    if 'images' in results:
        # Images usually (B, N, 3, H, W) -> permute to (B, N, H, W, 3)
        imgs = results['images']
        if imgs.shape[2] == 3: # Check if channel-first
            imgs = imgs.permute(0, 1, 3, 4, 2)
        colors = (imgs.float().numpy() * 255).astype(np.uint8)
    else:
        # Default to white if no image data saved
        colors = np.ones((B, N, H, W, 3), dtype=np.uint8) * 255

    return points, conf, poses, colors
